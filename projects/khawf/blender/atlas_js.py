#!/usr/bin/env python3
"""atlas_js.py: write js/atlas.js (MV.ATLAS + MV.MIRROR_OPENING) from assets/blender/*.json.
The linter cannot read JSON at render time, so the atlas geometry ships as a tiny generated script.
    python3 projects/khawf/blender/atlas_js.py      (render_all.sh runs it)"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
A = os.path.join(here, "..", "assets", "blender")
atl = {n: json.load(open(os.path.join(A, f"{n}_atlas.json"))) for n in ["lantern", "mirror", "crown", "hourglass"]}
op = json.load(open(os.path.join(A, "mirror_opening.json")))
with open(os.path.join(here, "..", "js", "atlas.js"), "w") as f:
    f.write("// generated by blender/atlas_js.py from assets/blender/*.json — do not edit by hand\n")
    f.write("window.MV = window.MV || {};\nMV.ATLAS = " + json.dumps(atl, separators=(",", ":")) + ";\n")
    f.write("MV.MIRROR_OPENING = " + json.dumps(op, separators=(",", ":")) + ";\n")
print("js/atlas.js written")
