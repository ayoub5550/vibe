#!/usr/bin/env python3
"""build_song_js.py — merge beat analysis + proof-read lyrics into analysis/song.json and js/song.js.

  python tools/build_song_js.py <project_dir>

Inputs (in <project_dir>/analysis/):
  song_raw.json  — output of tools/analyze_song.py (beats, energy, kicks, snares, words)
  lyrics.txt     — the sung lines in order, one per line; section headers in [brackets], e.g.
                   [hook1]
                   Mirror, mirror on the wall
                   ...
  sections.json  — [{"name": "hook1", "beats": [0, 32], "feel": "..."}, ...]  (you write this by
                   listening to the analysis: energy jumps, kick entries, where lines repeat)
Words are consumed in order, so every lyric line must have exactly as many words as were
transcribed for it; the script stops with MISMATCH if not — fix lyrics.txt or the words.
Outputs analysis/song.json (full) and js/song.js (compact, loaded by index.html).
"""
import json, os, sys


def main(pd):
    an = os.path.join(pd, "analysis")
    raw = json.load(open(os.path.join(an, "song_raw.json")))
    secs = json.load(open(os.path.join(an, "sections.json")))
    words = raw["words"]
    lines, sec, i = [], None, 0
    for ln in open(os.path.join(an, "lyrics.txt"), encoding="utf-8"):
        ln = ln.strip()
        if not ln:
            continue
        if ln.startswith("[") and ln.endswith("]"):
            sec = ln[1:-1]
            continue
        n = len(ln.split())
        ws = words[i:i + n]
        i += n
        norm = lambda x: x.replace('"', "").replace(",", "").lower()
        got = " ".join(w["w"] for w in ws)
        if norm(got) != norm(ln):
            sys.exit(f"MISMATCH line {len(lines)}: transcribed '{got}' vs lyrics '{ln}'")
        lines.append({"i": len(lines), "section": sec, "text": ln, "s": ws[0]["s"], "e": ws[-1]["e"],
                      "beat": ws[0]["beat"], "words": [{"w": w["w"], "s": w["s"], "e": w["e"]} for w in ws]})
    if i != len(words):
        sys.exit(f"{len(words) - i} transcribed words left over — lyrics.txt is incomplete")
    P, O = raw["beat_period"], raw["beat_offset"]
    for s in secs:
        s["s"] = round(max(0.0, O + s["beats"][0] * P), 3)
        s["e"] = round(min(raw["duration"], O + s["beats"][1] * P), 3)
    song = {"excerpt_seconds": raw["duration"], "bpm": raw["bpm"], "beat_period": P, "beat_offset": O,
            "beat_formula": "t(beat k) = beat_offset + k * beat_period", "sections": secs, "lines": lines,
            "beats": raw["beats"], "beat_energy": raw["beat_energy"], "kicks": raw["kicks"], "snares": raw["snares"]}
    json.dump(song, open(os.path.join(an, "song.json"), "w"), indent=1)
    compact = {k: song[k] for k in ["excerpt_seconds", "bpm", "beat_period", "beat_offset", "sections", "beat_energy", "kicks", "snares"]}
    compact["lines"] = [{"text": l["text"], "s": l["s"], "e": l["e"], "words": [[w["w"], w["s"], w["e"]] for w in l["words"]]} for l in lines]
    with open(os.path.join(pd, "js", "song.js"), "w") as f:
        f.write("// generated by tools/build_song_js.py from analysis/song.json — do not edit by hand\n")
        f.write("window.MV = window.MV || {};\nMV.SONG = " + json.dumps(compact, separators=(",", ":")) + ";\n")
    print(f"{len(lines)} lines, {len(words)} words -> analysis/song.json + js/song.js")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
